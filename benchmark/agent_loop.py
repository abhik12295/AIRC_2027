"""Offline, effect-graded LLM-agent episodes over synthetic tool interfaces.

Research warnings:
  - The step-zero denial is imposed by the evaluation, not generated by the LLM.
  - POLICY_DENIED and SERVICE_UNAVAILABLE denote different interventions.
  - task_policy uses a trusted effect oracle and is an *upper-bound reference*,
    not an independently learned or newly demonstrated security algorithm.
  - No real email, repos, users or cloud services are ever accessed.
"""
